import { launch, login, launchGame, waitAssets, me, ents, wait, setHud, zoomTo, cheat, sleep } from './lib.mjs';
const { browser, page } = await launch();
await page.goto('http://localhost:8080/?r=3d'); await sleep(3000);
await page.screenshot({ path: 'frames/ex_login.jpg', quality: 80 });
await login(page);
await launchGame(page);
await waitAssets(page, 2000);
console.log('zoom', await page.evaluate(() => [window.__game.world.zoom, window.__r3d?.man?.data?.camera]));
await setHud(page, 'none');
await zoomTo(page, 0.45, true); await wait(page, 0.5);
await page.screenshot({ path: 'frames/ex_zoomout.jpg', quality: 80 });
await zoomTo(page, 1.6, true); await wait(page, 0.5);
await page.screenshot({ path: 'frames/ex_zoomin.jpg', quality: 80 });
await setHud(page, 'full'); await zoomTo(page, 1, true);
await page.evaluate(() => window.__game.toggleHangar()); await wait(page, 1);
await page.screenshot({ path: 'frames/ex_hangar.jpg', quality: 80 });
await page.evaluate(() => window.__game.toggleHangar());
await page.evaluate(() => window.__game.warp(18)); await wait(page, 3);
const m = await me(page); console.log('after warp', m);
const es = await ents(page);
console.log('cubikons', es.filter(e => /ubikon/i.test(e.n)).map(e => [e.id, e.x|0, e.y|0, e.s]));
console.log('npc sample', [...new Set(es.map(e => e.n + '|' + e.s))].slice(0, 20));
await page.screenshot({ path: 'frames/ex_map18.jpg', quality: 80 });
await browser.close();
